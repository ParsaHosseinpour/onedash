/**
 * Monitor IDs are UUIDs generated by the database. Validate the shape before
 * sending an id to PostgREST so a malformed URL segment becomes a clean
 * not-found response instead of a database type error.
 */
const MONITOR_ID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export function isMonitorId(value: unknown): value is string {
  return typeof value === "string" && MONITOR_ID_PATTERN.test(value);
}

