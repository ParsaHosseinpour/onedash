export function monitorToFormValues(monitor: MonitorSummary): MonitorFormValues {
  return {
    name: monitor.name,
    url: monitor.url,
    method: monitor.method,
    expectedStatus: formatExpectedStatusInput(monitor.expectedStatusCodes),
    intervalMinutes: formatIntervalMinutesInput(monitor.intervalSeconds),
    timeoutSeconds: String(monitor.timeoutSeconds),
    initialState: monitor.isActive ? "active" : "paused",
  };
}

export function formatIntervalMinutesInput(seconds: number): string {
  return String(seconds / 60);
}

/**
 * Expands a single code, comma-separated codes, and inclusive ranges into the
 * database's expected_status_codes array. Callers enforce the 20-code cap.
 */
export function parseExpectedStatusCodes(value: string): {
  ok: true;
  codes: number[];
} | {
  ok: false;
  message: string;
} {
  const tokens = value
    .split(",")
    .map((token) => token.trim())
    .filter(Boolean);

  if (tokens.length === 0) {
    return {
      ok: false,
      message: "Enter a status code such as 200, or a range such as 200-204.",
    };
  }

  const codes = new Set<number>();

  for (const token of tokens) {
    const single = /^(\d{3})$/.exec(token);
    if (single) {
      const code = Number(single[1]);
      if (code < 100 || code > 599) {
        return { ok: false, message: "Status codes must be between 100 and 599." };
      }
      codes.add(code);
      continue;
    }

    const range = /^(\d{3})\s*-\s*(\d{3})$/.exec(token);
    if (range) {
      const start = Number(range[1]);
      const end = Number(range[2]);

      if (start < 100 || end > 599 || start > end) {
        return {
          ok: false,
          message:
            "Enter a valid status range between 100 and 599, with the lower number first.",
        };
      }

      for (let code = start; code <= end; code += 1) {
        codes.add(code);
        if (codes.size > MONITOR_MAX_EXPECTED_STATUS_CODES) {
          return {
            ok: false,
            message: `A status range can contain at most ${MONITOR_MAX_EXPECTED_STATUS_CODES} codes.`,
          };
        }
      }
      continue;
    }

    return {
      ok: false,
      message:
        "Use status codes such as 200, 204 or a range such as 200-204, separated by commas.",
    };
  }

  if (codes.size > MONITOR_MAX_EXPECTED_STATUS_CODES) {
    return {
      ok: false,
      message: `List at most ${MONITOR_MAX_EXPECTED_STATUS_CODES} status codes.`,
    };
  }

  return { ok: true, codes: [...codes].sort((a, b) => a - b) };
}

export function formatExpectedStatusInput(codes: number[]): string {
  return [...codes].sort((a, b) => a - b).join(", ");
}

export function formatExpectedStatuses(codes: number[]): string {
  const sorted = [...new Set(codes)].sort((a, b) => a - b);
  if (sorted.length === 0) return "None";

  const parts: string[] = [];
  let runStart = sorted[0];
  let runEnd = sorted[0];

  for (let index = 1; index < sorted.length; index += 1) {
    const code = sorted[index];
    if (code === runEnd + 1) {
      runEnd = code;
      continue;
    }

    parts.push(runStart === runEnd ? String(runStart) : `${runStart}–${runEnd}`);
    runStart = code;
    runEnd = code;
  }

  parts.push(runStart === runEnd ? String(runStart) : `${runStart}–${runEnd}`);
  return parts.join(", ");
}

export function formatCheckInterval(seconds: number): string {
  if (seconds % 3600 === 0) {
    const hours = seconds / 3600;
    return `${hours} hr${hours === 1 ? "" : "s"}`;
  }

  if (seconds % 60 === 0) {
    const minutes = seconds / 60;
    return `${minutes} min`;
  }

  return `${seconds} sec`;
}

export function formatTimestampUtc(value: string | null): string | null {
  if (!value) return null;

  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return null;

  return `${date.toLocaleString("en-US", {
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    timeZone: "UTC",
  })} UTC`;
}

